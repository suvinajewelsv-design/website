// Helper function to find product by ID (handles svj101, svj-101, SVJ101)
function findProductById(id) {
  if (!id) return null;
  const norm = String(id).toLowerCase().replace(/[^a-z0-9]/g, "");
  return JEWELRY_PRODUCTS.find(p => 
    p.id.toLowerCase().replace(/[^a-z0-9]/g, "") === norm || 
    p.code.toLowerCase().replace(/[^a-z0-9]/g, "") === norm
  );
}

